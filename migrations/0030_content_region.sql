--
-- 内容产地：作品属于哪个发行体系（日本／韩国／国产／欧美／其他）。
--
-- 为什么要这么改：在这之前账本里没有任何一列说得出一部片是哪来的，「是不是 JAV」
-- 完全由 `catalog_rules.is_jav_asset` 从番号形态加发行证据推出来。可番号形态是日本
-- 厂牌的写法，韩国 MIB 的 `CA-103` 和国产麻豆的 `MDX-0123` 与日本番号一模一样，
-- 于是只要刮削给它们回填了厂牌或发行日，它们就自动满足「JAV」的全部条件。
-- 2026-09-13 只读盘点：账本里 381 条 MIB 番号资产已有 115 条被判成 JAV，其余 266 条
-- 只是资料还没刮到，补齐后同样会进去。`is_korean_mib_code` 认得出这批片，但那份
-- 判断只接在刮削入口上，分类口径从来没读过它。
--
-- 取值集合（`jp`／`kr`／`cn`／`west`／`other`，空串是未判定）写在
-- `src/peach/regions.py`，不写成 `CHECK` 约束：将来真要把港台从国产里拆出来时，
-- 改一个 Python 常量就够了，不必为加一个取值再迁一次账本。
--
-- 为什么两张表都加：库里 23355 个视频只有 2320 个有番号，大头是创作者内容。这类片
-- 没有番号可推，但同一个创作者的作品产地是同一个，`entity.region` 让这个判断在实体
-- 上定一次、所有作品受益。`asset.region` 是最终结论，为空时按实体投影读。
--
-- 已有行一律留空，不回填、不推断。推断结果是候选，要经用户复核才落库——把猜出来的
-- 产地直接写进真相字段，等于用一次批量脚本把用户还没做的判断替他做了，而这一列的
-- 后果是「片从 JAV 页里消失」，猜错了不报错，只是再也找不到。

ALTER TABLE asset ADD COLUMN region TEXT;
ALTER TABLE entity ADD COLUMN region TEXT;

-- 产地筛选是列表页的常规条件，和 `location` 同级。
CREATE INDEX IF NOT EXISTS idx_asset_region ON asset(region) WHERE region IS NOT NULL;
