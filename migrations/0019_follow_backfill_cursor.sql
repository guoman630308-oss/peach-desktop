-- 追更来源的「往回抓」游标。
--
-- 常规检查永远只看第一页——追更关心的是增量，每次都从头翻一遍站点既慢又没必要。
-- 但因此每个来源就只有第一页那点内容：rule34video 的作者页一页 24 条，实际有 61 页；
-- rule34.xxx 一次 limit 100，而一个标签能有三千多条。用户看到的「怎么这么少」就是
-- 这个原因。
--
-- 所以往回抓是一个**独立的、显式的**动作：用户点一次，从这个游标的下一页取一页，
-- 取完游标加一。它和常规检查用同一套入库路径，区别只在起始页。
--
-- 游标从 0 开始，表示「只抓过第一页」。它记的是**已经抓到哪儿**，不是下次抓哪儿——
-- 这样新建来源不用写初始值，默认值就是对的。
