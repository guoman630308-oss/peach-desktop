--
-- 关注条目的按图隐藏：用户对单张图片说「这不是我要看的内容」。
--
-- 为什么要一列而不是塞进 metadata：metadata 整串由连接器在每次检查时重写，
-- 用户按下去的隐藏状态放进里面，下一轮抓取就会无声消失。它和 `status`、
-- `asset_id` 是同一类东西——用户的处理结果，抓取流程只读不写，所以进列、
-- 留在 `record()` 的两条 SET 子句之外。
--
-- 存的是媒体稳定键（`id` 优先、`url` 兜底）的 JSON 数组，不是序号：fanbox 的
-- imageMap id 跨抓取稳定，网盘与附件的 url 指向同一个文件；序号在作者增删
-- 图片后会错位。NULL 与空数组都表示什么也没隐藏，未隐藏过的行保持 NULL。
--
-- 隐藏只影响浏览面：轮播、卡片缩略图与详情侧栏不再显示这张图，ledger 行与
-- 原始媒体清单完整保留，随时可以撤销。
--

ALTER TABLE follow_item ADD COLUMN hidden_media_json TEXT;
