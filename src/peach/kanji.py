# 简体中文没有对应字形的日本汉字：咲 凪 雫 辻 笹 榊 槙 䌷。中文资料页一律照抄，
# 表里不收，逐字换的时候原样留下——`桜咲姫莉` 该变成 `樱咲姬莉`，不是变成半个空格。
_KANA = re.compile(r"[぀-ヿ]")
_LATIN = re.compile(r"[A-Za-z]")


def fold_glyphs(text: str) -> str:
    """逐字换字形，假名与拉丁字母原样留下。

    这是「比名字」用的形，不是落库用的形：`永瀬みなも` 折成 `永濑みなも` 只为了和
    `永瀨未萌` 对得上姓，半中半日的串不该写进账本。要落库的走 `simplify_kanji`。
    """
    out: list[str] = []
    for char in text or "":
        # 「々」是日语的叠字符号，中文没有这个写法，照抄下来 `野々宮蘭` 就还是半个
        # 日文名。它的意思是「重复上一个字」，展开成 `野野宫兰` 没有任何判断空间。
        if char == "々" and out:
            out.append(out[-1])
            continue
        out.append(JP_KANJI_TO_SIMPLIFIED.get(char, char))
    return "".join(out)


def simplify_kanji(name: str) -> str:
    """把纯汉字姓名里的日本字形换成简体字形；含假名或拉丁字母的名字原样返回。

    假名和罗马字要的是译名，不是字形：`飯岡かなこ` 逐字换只得到 `饭冈かなこ`，
    一个半中半日的名字，比原样留着更糟。那种名字只能等外部来源给出中文写法。
    """
    if not name or _KANA.search(name) or _LATIN.search(name):
        return name
    return fold_glyphs(name)
